#!/usr/bin/env python3
"""Writes runtime/interp_patches.c: the interpreter's version of tools/patches.py (instruction replacements and hook
sites) for every game version in runtime/game_addresses/versions.h, and the randomizer patch sites from
tools/rando/patch_variants.json. Needs no game binary.

Each PATCHES entry makes C for the generated code; here the same C becomes a function `uint64_t p_<addr>(Cpu *c)`:
0 = go on with the next instruction, 1 = return from the guest function (the `return;` of the generated code), any
other value = continue at that guest address (the `goto L_<addr>;` of the generated code). The few patches that
depend on the register numbers of the original instruction (not in the sources: the game binary isn't needed here)
read them from the instruction word at run time.
"""
import json
import os
import re
import struct
import sys

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import game_addresses as GA  # noqa: E402
GA.select_version(next(iter(GA.VERSIONS)))  # (patches.py builds its tables from the selected version on import)
import patches as P  # noqa: E402
import importlib  # noqa: E402


class W(int):
    """Stands for the instruction word: every comparison holds, the compared constants are recorded."""
    rec = None

    def __eq__(self, o):
        if W.rec is not None and not getattr(self, 'derived', False):
            W.rec.append(int(o))
        return True

    __hash__ = int.__hash__

    def _mk(self, v):
        x = W(v)
        x.derived = True
        return x

    def __and__(self, o): return self._mk(int(self) & int(o))
    def __rshift__(self, o): return self._mk(int(self) >> int(o))
    def __or__(self, o): return self._mk(int(self) | int(o))
    def __lshift__(self, o): return self._mk(int(self) << int(o))


class Gen:
    class nso:
        image = b''
    base = 0


def word_for(fn, a):
    """The instruction word the patch asserts (when it asserts one exactly), else None."""
    rec = []
    orig = P.struct.unpack_from
    P.struct.unpack_from = lambda fmt, buf, off: (W(0),)
    W.rec = rec
    try:
        fn(Gen, a)
    finally:
        W.rec = None
        P.struct.unpack_from = orig
    return rec[0] if rec else None


def code_for(fn, a):
    wv = word_for(fn, a)
    orig = P.struct.unpack_from
    P.struct.unpack_from = lambda fmt, buf, off: (W(wv or 0),)
    try:
        return fn(Gen, a)
    finally:
        P.struct.unpack_from = orig



def build(key):
    """The replacements and hook sites of game version `key`: ({addr: C body}, {addr: (word, targets)})."""
    GA.select_version(key)
    importlib.reload(P)
    special = {}
    for a in P.ASPECT_SITES:
        special[a] = ('{ extern float rt_aspect_site(int); float f = rt_aspect_site(%d); int rt = *(const uint32_t *)(uintptr_t)%#xull & 31; '
                      'c->v[rt] = 0; memcpy(&c->v[rt], &f, 4); }' % (P.ASPECT_SITES[a], a))
    special[P.INDOOR_SITE] = ('{ extern float rt_indoor_aspect(void); float f = rt_indoor_aspect(); '
                              'int rt = *(const uint32_t *)(uintptr_t)%#xull & 31; c->v[rt] = 0; memcpy(&c->v[rt], &f, 4); }' % P.INDOOR_SITE)
    for a in P.DAMAGE_LSL_SITES:
        special[a] = ('{ extern int32_t rt_damage(int32_t, int32_t); uint32_t w = *(const uint32_t *)(uintptr_t)%#xull; '
                      'c->x[w & 31] = (uint32_t)rt_damage((int32_t)c->x[(w >> 5) & 31], (int32_t)(c->x[(w >> 16) & 31] & 31)); }' % a)
    bodies = {}
    for a in sorted(P.PATCHES):
        code = special.get(a)
        if code is None:
            code = code_for(P.PATCHES[a], a)
            if word_for(P.PATCHES[a], a) is None:  # (no exact word asserted: the code must not depend on the word)
                orig = P.struct.unpack_from
                P.struct.unpack_from = lambda fmt, buf, off: (W(0xFFFFFFFF),)
                try:
                    other = P.PATCHES[a](Gen, a)
                finally:
                    P.struct.unpack_from = orig
                if other != code:
                    sys.exit('patch %#x (%s) depends on the register fields of its instruction: give it a SPECIAL '
                             'entry that reads the word at run time' % (a, key))
        bodies[a] = code
    hooks = {a: (w, tuple(t)) for a, (w, t, _) in P.HOOKS.items()}
    return bodies, hooks


versions = {}
for key in GA.VERSIONS:
    versions[key] = build(key)

out = ['// Generated by tools/gen_interp_patches.py from tools/patches.py and tools/rando/patch_variants.json: do not edit.',
       '// The interpreter\'s per-instruction replacements and hook sites, per game version (see interp.h).',
       '#include <string.h>', '', '#include "cpu.h"', '#include "interp.h"', '#include "rando.h"', '#include "rt.h"', '',
       'static uint64_t adds64_(Cpu *c, uint64_t x, uint64_t y);', '']
# one C function per distinct replacement (the two versions share most: only the addresses differ)
fn_of = {}   # cleaned code -> name
fnames = set()
decls = []
for key, (bodies, hooks) in versions.items():
    for a, code in bodies.items():
        code = re.sub(r'/\*.*?\*/', '', code, flags=re.S)
        code = re.sub(r'extern void (f_[0-9a-f]+)\(Cpu \*\);', '', code)
        fnames.update(re.findall(r'\b(f_[0-9a-f]+)\(c\)', code))
        code = re.sub(r'goto L_([0-9a-f]+);', lambda m: 'return 0x%sull;' % m.group(1), code)
        code = re.sub(r'\breturn;', 'return 1;', code)
        code = code.strip()
        if code not in fn_of:
            fn_of[code] = 'p_%d' % len(fn_of)
        bodies[a] = fn_of[code]
out.append('// guest functions the replacements call')
for f in sorted(fnames):
    out.append('static void %s(Cpu *c) { c->pc = 0x%sull; rt_dispatch(c); }' % (f, f[2:]))
out.append('')
for code, name in fn_of.items():
    out.append('static uint64_t %s(Cpu *c) {\n    %s\n    return 0;\n}' % (name, code))
out.append('')
for key, (bodies, hooks) in versions.items():
    out.append('static const InterpPatch patches_%s[] = {' % key)
    for a in sorted(bodies):
        out.append('    {0x%xull, %s},' % (a, bodies[a]))
    out.append('};')
    for i, a in enumerate(sorted(hooks)):
        t = hooks[a][1]
        if t:
            out.append('static const uint64_t hook_targets_%s_%d[] = {%s};' % (key, i, ', '.join('0x%xull' % x for x in t)))
    out.append('static const InterpHook hooks_%s[] = {' % key)
    for i, a in enumerate(sorted(hooks)):
        w, t = hooks[a]
        out.append('    {0x%xull, 0x%08x, %s, %d},' % (a, w, 'hook_targets_%s_%d' % (key, i) if t else 'NULL', len(t)))
    out.append('};')
out.append('const InterpVersion interp_versions[] = {')
for key, (bodies, hooks) in versions.items():
    out.append('    {"%s", patches_%s, %d, hooks_%s, %d},' % (key, key, len(bodies), key, len(hooks)))
out.append('};')
out.append('const int interp_version_count = %d;' % len(versions))
out.append('')
rv = json.load(open(os.path.join(here, 'rando', 'patch_variants.json')))['code']
for i, (a, ws) in enumerate(sorted(rv.items(), key=lambda kv: int(kv[0], 16))):
    out.append('static const uint32_t rw_%d[] = {%s};' % (i, ', '.join(ws)))
out.append('const InterpRandoSite interp_rando_sites[] = {')
for i, (a, ws) in enumerate(sorted(rv.items(), key=lambda kv: int(kv[0], 16))):
    out.append('    {MAIN_BASE + %sull, rw_%d, %d},' % (a, i, len(ws)))
out.append('};')
out.append('const int interp_rando_count = %d;' % len(rv))
text = '\n'.join(out).replace('static uint64_t adds64_(Cpu *c, uint64_t x, uint64_t y);\n', '') + '\n'
open(os.path.join(os.path.dirname(here), 'runtime', 'interp_patches.c'), 'w').write(text)
print(', '.join('%s: %d patches, %d hooks' % (k, len(b), len(h)) for k, (b, h) in versions.items()), '|', len(rv), 'rando sites')
